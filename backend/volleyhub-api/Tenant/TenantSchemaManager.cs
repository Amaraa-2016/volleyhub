    public Task CreateSchemaForTenant(string schemaName, int tenantId)
        => CreateSchemaForTenant(schemaName, tenantId, seedDemoData: true);

    // Self-service club creation passes seedDemoData:false - tables and reference data only. The
    // creator is added as Admin separately via ProvisionStaff.
    public async Task CreateSchemaForTenant(string schemaName, int tenantId, bool seedDemoData)
    {
        await using var conn = new NpgsqlConnection(_connectionString);
        await conn.OpenAsync();

        await using (var createSchemaCmd = conn.CreateCommand())
        {
            createSchemaCmd.CommandText = $"CREATE SCHEMA IF NOT EXISTS \"{schemaName}\"";
            await createSchemaCmd.ExecuteNonQueryAsync();
        }

        var options = new DbContextOptionsBuilder<VolleyDbContext>()
            .UseNpgsql(_connectionString)
            .ReplaceService<IModelCacheKeyFactory, SchemaAwareModelCacheKeyFactory>()
            .Options;
        await using (var context = new VolleyDbContext(options, new FixedTenantProvider(schemaName)))
        {
            await CreateOrSyncContextAsync(conn, context, schemaName);
        }

        await SeedSchemaDataAsync(conn, schemaName, seedDemoData);
    }

    // Insert (or reuse) one staff row inside tenant_<id> for an account, returning its staffid.
    // Idempotent on (phone, tenantid) so a retry never duplicates.
    public async Task<int> ProvisionStaff(string schemaName, int tenantId, string phone, string? name,
        string encryptedPassword, int roleid, string? lastname = null, string? firstname = null, int accountId = 0)
    {
        await using var conn = new NpgsqlConnection(_connectionString);
        await conn.OpenAsync();

        await using (var check = conn.CreateCommand())
        {
            check.CommandText = $"SELECT staffid FROM \"{schemaName}\".\"staff\" WHERE phone = @phone AND tenantid = @tid LIMIT 1";
            check.Parameters.AddWithValue("phone", phone);
            check.Parameters.AddWithValue("tid", tenantId);
            var existing = await check.ExecuteScalarAsync();
            if (existing != null && existing != DBNull.Value)
                return Convert.ToInt32(existing);
        }

        await using (var ins = conn.CreateCommand())
        {
            ins.CommandText = $"""
                INSERT INTO "{schemaName}"."staff"
                    (accountid, phone, staffname, lastname, firstname, password, isactive, roleid, tenantid, created)
                VALUES (@acc, @phone, @name, @lastname, @firstname, @pwd, true, @role, @tid, now())
                RETURNING staffid
                """;
            ins.Parameters.AddWithValue("acc", accountId);
            ins.Parameters.AddWithValue("phone", phone);
            ins.Parameters.AddWithValue("name", (object?)name ?? DBNull.Value);
            ins.Parameters.AddWithValue("lastname", (object?)lastname ?? DBNull.Value);
            ins.Parameters.AddWithValue("firstname", (object?)firstname ?? DBNull.Value);
            ins.Parameters.AddWithValue("pwd", encryptedPassword);
            ins.Parameters.AddWithValue("role", roleid);
            ins.Parameters.AddWithValue("tid", tenantId);
            var id = await ins.ExecuteScalarAsync();
            return Convert.ToInt32(id);
        }
    }

    // Create this context's tables fresh when none exist yet, otherwise add whatever is missing.
    private static async Task CreateOrSyncContextAsync(NpgsqlConnection conn, DbContext context, string schemaName)
    {
        var tableNames = context.Model.GetEntityTypes()
            .Select(e => e.GetTableName())
            .Where(n => n is not null)
            .Distinct()
            .ToArray();

        long existing;
        await using (var checkCmd = conn.CreateCommand())
        {
            checkCmd.CommandText =
                "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = @schema AND table_name = ANY(@names)";
            checkCmd.Parameters.AddWithValue("schema", schemaName);
            checkCmd.Parameters.AddWithValue("names", tableNames!);
            existing = (long)(await checkCmd.ExecuteScalarAsync())!;
        }

        if (existing == 0)
        {
            var creator = context.GetInfrastructure().GetRequiredService<IRelationalDatabaseCreator>();
            await creator.CreateTablesAsync();
        }
        else
        {
            await SyncSchemaColumnsAsync(conn, context, schemaName);
        }
    }

    // Add missing tables/columns and drop the ones the model no longer has. A cheap stand-in for
    // migrations, which cannot express "one model, N schemas".
    private static async Task SyncSchemaColumnsAsync(NpgsqlConnection conn, DbContext context, string schemaName)
    {
        foreach (var entityType in context.Model.GetEntityTypes())
        {
            var tableName = entityType.GetTableName();
            if (tableName is null) continue;

            var storeObject = StoreObjectIdentifier.Table(tableName, schemaName);
            var pkProperties = entityType.FindPrimaryKey()?.Properties.ToHashSet() ?? [];

            var columns = new List<(string columnName, string storeType, bool isPk, bool isIdentity, bool isBool)>();
            foreach (var property in entityType.GetProperties())
            {
                var columnName = property.GetColumnName(storeObject);
                if (columnName is null) continue;

                var storeType = property.GetColumnType() ?? property.GetRelationalTypeMapping().StoreType;
                var isPk = pkProperties.Contains(property);
                var isIdentity = isPk && property.ValueGenerated == ValueGenerated.OnAdd;
                var isBool = property.ClrType == typeof(bool) && !property.IsNullable;

                columns.Add((columnName, storeType, isPk, isIdentity, isBool));
            }

            if (columns.Count == 0) continue;

            var columnDefs = columns.Select(col =>
            {
                var def = $"\"{col.columnName}\" {col.storeType}";
                if (col.isIdentity) def += " GENERATED BY DEFAULT AS IDENTITY";
                if (col.isBool) def += " NOT NULL DEFAULT false";
                return def;
            });
            var pkCols = columns.Where(col => col.isPk).Select(col => $"\"{col.columnName}\"");
            var pkClause = pkCols.Any() ? $", PRIMARY KEY ({string.Join(", ", pkCols)})" : "";

            await using (var createCmd = conn.CreateCommand())
            {
                createCmd.CommandText = $"""
                    CREATE TABLE IF NOT EXISTS "{schemaName}"."{tableName}" (
                        {string.Join(",\n    ", columnDefs)}{pkClause}
                    )
                    """;
                await createCmd.ExecuteNonQueryAsync();
            }

            foreach (var (columnName, storeType, _, _, isBool) in columns)
            {
                var boolConstraint = isBool ? " NOT NULL DEFAULT false" : "";
                await using var alterCmd = conn.CreateCommand();
                alterCmd.CommandText = $"""
                    ALTER TABLE "{schemaName}"."{tableName}"
                    ADD COLUMN IF NOT EXISTS "{columnName}" {storeType}{boolConstraint}
                    """;
                await alterCmd.ExecuteNonQueryAsync();
            }

            var dbColumns = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            await using (var colsCmd = conn.CreateCommand())
            {
                colsCmd.CommandText = """
                    SELECT column_name
                    FROM information_schema.columns
                    WHERE table_schema = @schema AND table_name = @table
                    """;
                colsCmd.Parameters.AddWithValue("schema", schemaName);
                colsCmd.Parameters.AddWithValue("table", tableName);
                await using var reader = await colsCmd.ExecuteReaderAsync();
                while (await reader.ReadAsync())
                    dbColumns.Add(reader.GetString(0));
            }

            var modelColumns = new HashSet<string>(
                columns.Select(col => col.columnName),
                StringComparer.OrdinalIgnoreCase);

            foreach (var staleCol in dbColumns.Except(modelColumns))
            {
                await using var dropCmd = conn.CreateCommand();
                dropCmd.CommandText = $"""
                    ALTER TABLE "{schemaName}"."{tableName}"
                    DROP COLUMN IF EXISTS "{staleCol}"
                    """;
                await dropCmd.ExecuteNonQueryAsync();
            }
        }
    }

    // Reference data (roles) is always seeded; demo business data only for the demo club.
    private static async Task SeedSchemaDataAsync(NpgsqlConnection conn, string s, bool seedDemoData)
    {
        await using (var roles = conn.CreateCommand())
        {
            roles.CommandText = $"""
                INSERT INTO "{s}"."role" (roleid, rolename) VALUES
                    (1, 'Admin'), (2, 'Manager'), (3, 'Coach'), (4, 'Staff')
                ON CONFLICT (roleid) DO NOTHING;
                SELECT setval(pg_get_serial_sequence('"{s}"."role"', 'roleid'),
                              GREATEST((SELECT COALESCE(MAX(roleid), 0) FROM "{s}"."role"), 1));
                """;
            await roles.ExecuteNonQueryAsync();
        }

        if (!seedDemoData) return;

        // A centre with no hall cannot schedule anything, so the demo tenant gets one to make the
        // schedule screens usable straight after a fresh install.
        await using (var venue = conn.CreateCommand())
        {
            venue.CommandText = $"""
                INSERT INTO "{s}"."venue" (name, courts, is_deleted, created, updated)
                SELECT 'Үндсэн заал', 1, false, now(), now()
                WHERE NOT EXISTS (SELECT 1 FROM "{s}"."venue")
                """;
            await venue.ExecuteNonQueryAsync();
        }
    }
