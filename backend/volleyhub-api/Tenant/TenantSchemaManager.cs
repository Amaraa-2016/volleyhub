// Owns every piece of DDL in the system. The public schema is bootstrapped with raw, idempotent
// SQL (two EF contexts map public.tenant, so migration history would fight over it), and each club
// schema is created or column-synced straight from the EF model.
public class TenantSchemaManager
{
    private readonly string _connectionString;

    public TenantSchemaManager(IConfiguration config)
    {
        _connectionString = config["ConnectionStrings:dbCon"]!;
    }

    // public.tenant - the club registry.
    public async Task EnsureSharedSchema()
    {
        await using var conn = new NpgsqlConnection(_connectionString);
        await conn.OpenAsync();

        await using var cmd = conn.CreateCommand();
        cmd.CommandText = """
            CREATE TABLE IF NOT EXISTS public.tenant (
                tenantid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                tenantname character varying(200) NOT NULL,
                isactive boolean NOT NULL DEFAULT true
            );
            ALTER TABLE public.tenant ADD COLUMN IF NOT EXISTS isactive boolean NOT NULL DEFAULT true;
            INSERT INTO public.tenant (tenantid, tenantname, isactive)
            VALUES (1, 'Demo Volleyball Club', true)
            ON CONFLICT DO NOTHING;
            SELECT setval(pg_get_serial_sequence('public.tenant', 'tenantid'),
                          GREATEST((SELECT COALESCE(MAX(tenantid), 0) FROM public.tenant), 1));
            """;
        await cmd.ExecuteNonQueryAsync();
    }

