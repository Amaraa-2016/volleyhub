    public async Task<object> AddSamples(List<SkillRT> skills)
    {
        var skillIds = skills.GroupBy(k => k.name.Trim()).ToDictionary(g => g.Key, g => g.First().skillid);
        var now = DateTime.UtcNow;

        var existingDrills = await _db.drill.Where(d => !d.is_deleted).ToListAsync();
        var byName = existingDrills.GroupBy(d => d.name.Trim()).ToDictionary(g => g.Key, g => g.First());

        var drillsAdded = 0;
        foreach (var s in SampleDrills)
        {
            if (byName.ContainsKey(s.Name)) continue;
            var drill = new Drill
            {
                name = s.Name,
                minutes = s.Minutes,
                level = s.Level,
                equipment = s.Equipment.Length > 0 ? s.Equipment : null,
                description = s.Description,
                skills = string.Join(",", s.Skills.Where(skillIds.ContainsKey).Select(n => skillIds[n])),
                created = now,
                updated = now,
            };
            _db.drill.Add(drill);
            byName[s.Name] = drill;
            drillsAdded++;
        }
        await _db.SaveChangesAsync();

        var planNames = (await _db.plan.Where(p => !p.is_deleted).Select(p => p.name).ToListAsync())
            .Select(n => n.Trim()).ToHashSet();

        var plansAdded = 0;
        foreach (var p in SamplePlans)
        {
            if (planNames.Contains(p.Name)) continue;
            await SavePlan(new PlanBT
            {
                name = p.Name,
                notes = p.Notes,
                items = p.Steps.Select(step => new PlanItemBT
                {
                    title = step.Title,
                    minutes = step.Minutes,
                    drillid = byName.TryGetValue(step.Title, out var d) ? d.drillid : null,
                }).ToList(),
            });
            plansAdded++;
        }

        return new { drills = drillsAdded, plans = plansAdded };
    }
